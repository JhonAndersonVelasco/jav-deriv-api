"""
deriv-setup — interactive wizard to create / update the project .env file.

Usage:
    deriv-setup
"""

from __future__ import annotations

import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _project_root() -> Path:
    """Return the directory that contains pyproject.toml / setup.cfg, or CWD."""
    here = Path(__file__).parent  # deriv_api/
    # Walk up looking for pyproject.toml
    for candidate in [here.parent, here]:
        if (candidate / "pyproject.toml").exists() or (candidate / "setup.cfg").exists():
            return candidate
    return Path.cwd()


def _ask(prompt: str, default: str = "", secret: bool = False) -> str:
    """Prompt the user, returning stripped input or *default* on empty input."""
    hint = f" [{default}]" if default and not secret else ""
    full_prompt = f"{prompt}{hint}: "
    try:
        if secret:
            import getpass

            value = getpass.getpass(full_prompt)
        else:
            value = input(full_prompt)
    except (KeyboardInterrupt, EOFError):
        print("\nSetup cancelled.")
        sys.exit(0)
    return value.strip() or default


def _confirm(prompt: str, default: bool = True) -> bool:
    hint = "[Y/n]" if default else "[y/N]"
    answer = _ask(f"{prompt} {hint}").lower()
    if not answer:
        return default
    return answer in ("y", "yes")


def _parse_env(path: Path) -> dict[str, str]:
    """Parse an existing .env file into a dict."""
    result: dict[str, str] = {}
    if not path.exists():
        return result
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            key, _, value = line.partition("=")
            result[key.strip()] = value.strip().strip('"').strip("'")
    return result


def _write_env(path: Path, values: dict[str, str]) -> None:
    """Write *values* to *path* as KEY=value lines."""
    lines = [
        "# Deriv API configuration — generated by deriv-setup",
        "# Keep this file private and never commit it to version control.",
        "",
    ]
    for key, value in values.items():
        lines.append(f'{key}="{value}"')
    path.write_text("\n".join(lines) + "\n")


def _ensure_gitignore(root: Path) -> None:
    """Add .env to .gitignore if not already present."""
    gitignore = root / ".gitignore"
    entry = ".env"
    if gitignore.exists():
        content = gitignore.read_text()
        if entry in content.splitlines():
            return
        gitignore.write_text(content.rstrip() + f"\n{entry}\n")
    else:
        gitignore.write_text(f"{entry}\n")
    print(f"  ✓ Added '{entry}' to {gitignore.relative_to(root)}")


# ---------------------------------------------------------------------------
# Field definitions
# ---------------------------------------------------------------------------


def _validate_min_len(v: str) -> bool:
    return len(v) > 10


def _validate_non_empty(v: str) -> bool:
    return bool(v.strip())


def _validate_ws_endpoint(v: str) -> bool:
    return v.startswith("wss://") or v.startswith("ws://")


@dataclass
class FieldDef:
    key: str
    label: str
    help: str = ""
    required: bool = False
    secret: bool = False
    default: str = ""
    validate: Callable[[str], bool] | None = None
    validate_msg: str = "Invalid value."


FIELDS: list[FieldDef] = [
    FieldDef(
        key="DERIV_TOKEN",
        label="Deriv Personal Access Token (PAT)",
        help=(
            "Used for WebSocket API authentication (examples 02, 03).\n"
            "  Get it from: https://app.deriv.com/account/api-token\n"
            "  Scopes needed: read + trade"
        ),
        required=True,
        secret=True,
        validate=_validate_min_len,
        validate_msg="Token looks too short — please double-check.",
    ),
    FieldDef(
        key="DERIV_OAUTH_TOKEN",
        label="Deriv OAuth2 Bearer token (optional)",
        help=(
            "Used for REST API authentication (example 04).\n"
            "  Obtained via OAuth2 Authorization Code + PKCE flow:\n"
            "    Auth:  https://auth.deriv.com/oauth2/auth\n"
            "    Token: https://auth.deriv.com/oauth2/token\n"
            "  Leave blank to skip REST API examples."
        ),
        required=False,
        secret=True,
        default="",
        validate=_validate_min_len,
        validate_msg="Token looks too short — please double-check.",
    ),
    FieldDef(
        key="DERIV_APP_ID",
        label="Application ID",
        help=(
            "Your app_id from https://developers.deriv.com (leave blank to use public demo ID 1089)"
        ),
        required=False,
        secret=False,
        default="1089",
        validate=_validate_non_empty,
        validate_msg="App ID cannot be empty.",
    ),
    FieldDef(
        key="DERIV_ENDPOINT",
        label="WebSocket endpoint",
        help="Leave blank for the default production endpoint.",
        required=False,
        secret=False,
        default="wss://red.derivws.com/websockets/v3",
        validate=_validate_ws_endpoint,
        validate_msg="Endpoint must start with wss:// or ws://",
    ),
]


# ---------------------------------------------------------------------------
# Main wizard
# ---------------------------------------------------------------------------


def main() -> None:
    print("=" * 60)
    print("  deriv-setup — Deriv API configuration wizard")
    print("=" * 60)

    root = _project_root()
    env_path = root / ".env"

    existing = _parse_env(env_path)
    if existing:
        print(f"\nFound existing .env at: {env_path}")
        if not _confirm("Update it?"):
            print("Nothing changed.")
            sys.exit(0)
    else:
        print(f"\nWill create: {env_path}\n")

    collected: dict[str, str] = {}

    for field in FIELDS:
        key = field.key
        label = field.label
        secret = field.secret
        required = field.required
        default = existing.get(key, field.default)
        help_text = field.help

        print(f"\n{label}")
        if help_text:
            for line in help_text.splitlines():
                print(f"  {line}")

        while True:
            value = _ask(f"  → {key}", default=default, secret=secret)

            if not value:
                if required:
                    print("  ✗ This field is required.")
                    continue
                else:
                    # Use default silently
                    value = default
                    break

            validator = field.validate
            if validator and not validator(value):
                print(f"  ✗ {field.validate_msg}")
                continue

            break

        if value:
            collected[key] = value

    # Preview
    print("\n" + "-" * 60)
    print("Values to write:")
    for k, v in collected.items():
        display = ("*" * min(len(v), 8) + "…") if k == "DERIV_TOKEN" else v
        print(f"  {k} = {display}")
    print(f"  File: {env_path}")
    print("-" * 60)

    if not _confirm("\nSave?"):
        print("Aborted — nothing written.")
        sys.exit(0)

    _write_env(env_path, collected)
    print(f"\n  ✓ Saved {env_path}")

    _ensure_gitignore(root)

    print("\nAll done! You can now run the examples:")
    print("  python -m deriv_api.examples.02_balance_and_buy\n")


if __name__ == "__main__":
    main()
